// Writes dist/licenses.txt: the name, version, license and full license text of
// every package esbuild actually bundled into dist/index.js (read from the build's
// metafile). MIT and similar licenses require their notice to ship with copies.
// Fails the build if a bundled package has no license file. Run by `npm run build`.
// ==========================================================================
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const METAFILE = 'node_modules/.cache/quandle/esbuild-meta.json';
const OUTPUT = 'dist/licenses.txt';
const LICENSE_FILE = /^(licen[sc]e|copying)(\.(md|txt))?$/i;

// "node_modules/@actions/core/lib/core.js" -> "node_modules/@actions/core" (handles nesting).
function readPackageDirectory(inputPath) {
  const parts = inputPath.split('/');
  const last = parts.lastIndexOf('node_modules');
  if (last < 0) return undefined;
  const nameLength = parts[last + 1]?.startsWith('@') ? 2 : 1;
  return parts.slice(0, last + 1 + nameLength).join('/');
}

const inputs = Object.keys(JSON.parse(readFileSync(METAFILE, 'utf8')).inputs);
const packageDirectories = [...new Set(inputs.map(readPackageDirectory).filter(Boolean))];

const problems = [];
const sections = packageDirectories
  .map((directory) => {
    const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    const licenseFile = readdirSync(directory).find((name) => LICENSE_FILE.test(name));
    if (licenseFile === undefined) {
      problems.push(`${manifest.name}@${manifest.version} (${directory}) has no license file`);
      return undefined;
    }
    const text = readFileSync(join(directory, licenseFile), 'utf8').trim();
    return { name: manifest.name, version: manifest.version, license: manifest.license ?? 'see text', text };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

if (problems.length > 0 || !existsSync('dist')) {
  console.error('Cannot write third-party licenses:');
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

const divider = '-'.repeat(78);
const body = sections
  .map((s) => `${divider}\n${s.name}@${s.version} (${s.license})\n${divider}\n\n${s.text}\n`)
  .join('\n');
writeFileSync(
  OUTPUT,
  `Third-party software bundled into dist/index.js, with each package's license.\n` +
    `Generated by scripts/write-third-party-licenses.mjs during npm run build. Do not edit.\n\n${body}`,
);
console.log(`Wrote ${OUTPUT}: ${sections.map((s) => `${s.name}@${s.version}`).join(', ')}`);
